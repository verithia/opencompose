//! Physical parameter units shared by mixer devices, synths and tool catalogs.
use serde::Serialize;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
/// Physical unit of a parameter.
pub enum Unit {
    #[serde(rename = "none")]
    None,
    #[serde(rename = "Hz")]
    Hz,
    #[serde(rename = "dB")]
    Db,
    #[serde(rename = "ms")]
    Ms,
    #[serde(rename = "%")]
    Percent,
    /// A stored fraction: 0.4 is displayed as 40%, without changing its value.
    #[serde(rename = "fraction")]
    Fraction,
    #[serde(rename = "ratio")]
    Ratio,
    #[serde(rename = "s")]
    Seconds,
    #[serde(rename = "ct")]
    Cents,
    #[serde(rename = "st")]
    Semitones,
    #[serde(rename = "oct")]
    Octaves,
    #[serde(rename = "deg")]
    Degrees,
}

#[derive(Debug, Clone, Copy, Serialize)]
#[serde(rename_all = "camelCase")]
/// Display and write metadata for one unit.
pub struct UnitDefinition {
    pub id: Unit,
    pub display_unit: &'static str,
    pub display_multiplier: f64,
    /// Suffix for new physical parameter writes. Fractions use bare numbers.
    pub write_suffix: &'static str,
}

impl Unit {
    /// Every unit a serialized parameter may name.
    pub const ALL: [Self; 12] = [
        Self::None,
        Self::Hz,
        Self::Db,
        Self::Ms,
        Self::Percent,
        Self::Fraction,
        Self::Ratio,
        Self::Seconds,
        Self::Cents,
        Self::Semitones,
        Self::Octaves,
        Self::Degrees,
    ];

    /// Stable unit id.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::None => "none",
            Self::Hz => "Hz",
            Self::Db => "dB",
            Self::Ms => "ms",
            Self::Percent => "%",
            Self::Fraction => "fraction",
            Self::Ratio => "ratio",
            Self::Seconds => "s",
            Self::Cents => "ct",
            Self::Semitones => "st",
            Self::Octaves => "oct",
            Self::Degrees => "deg",
        }
    }

    /// Display multiplier, suffix and write suffix for the unit.
    pub const fn definition(self) -> UnitDefinition {
        UnitDefinition {
            id: self,
            display_unit: match self {
                Self::None => "",
                Self::Fraction | Self::Percent => "%",
                Self::Ratio => ":1",
                Self::Degrees => "°",
                _ => self.as_str(),
            },
            display_multiplier: if matches!(self, Self::Fraction) {
                100.0
            } else {
                1.0
            },
            write_suffix: match self {
                Self::None | Self::Fraction | Self::Ratio => "",
                _ => self.as_str(),
            },
        }
    }
}

/// Every unit definition indexed like `Unit::ALL`.
pub const DEFINITIONS: &[UnitDefinition] = &[
    Unit::None.definition(),
    Unit::Hz.definition(),
    Unit::Db.definition(),
    Unit::Ms.definition(),
    Unit::Percent.definition(),
    Unit::Fraction.definition(),
    Unit::Ratio.definition(),
    Unit::Seconds.definition(),
    Unit::Cents.definition(),
    Unit::Semitones.definition(),
    Unit::Octaves.definition(),
    Unit::Degrees.definition(),
];

/// Browser types and display metadata come from exactly the same unit table.
pub fn render_typescript() -> String {
    let ids = DEFINITIONS
        .iter()
        .map(|entry| format!("\"{}\"", entry.id.as_str()))
        .collect::<Vec<_>>()
        .join(" | ");
    let json =
        serde_json::to_string_pretty(DEFINITIONS).expect("unit definitions are serializable");
    format!(
        "// @generated by `cargo run -p oc-device-schema --bin gen-device-catalog`.\n// Source of truth: crates/oc-device-schema/src/units.rs. Do not edit by hand.\n\nexport type UnitId = {ids};\nexport interface UnitDefinition {{\n  id: UnitId;\n  displayUnit: string;\n  displayMultiplier: number;\n  writeSuffix: string;\n}}\nexport const UNIT_DEFINITIONS: UnitDefinition[] = {json};\nexport function unitDefinition(unit: UnitId): UnitDefinition {{\n  return UNIT_DEFINITIONS.find((entry) => entry.id === unit)!;\n}}\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn fractions_scale_display_only_and_keep_native_percentages_distinct() {
        let fraction = Unit::Fraction.definition();
        for (physical, display) in [(0.4, 40.0), (1.5, 150.0), (-0.4, -40.0)] {
            assert_eq!(physical * fraction.display_multiplier, display);
        }
        assert_eq!(fraction.write_suffix, "");
        assert_eq!(Unit::Percent.definition().display_multiplier, 1.0);
        assert_eq!(Unit::Percent.definition().write_suffix, "%");
    }
    #[test]
    fn generated_unit_typescript_is_current() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../oc-gui/frontend/src/data/units.gen.ts");
        assert_eq!(
            std::fs::read_to_string(path).expect("generated units exist"),
            render_typescript()
        );
    }
}
