#!/usr/bin/env bash
# Build or serve the documentation site.
#
# Layout of the published artifact:
#
#   book/            the mdBook built from docs/
#   book/api/        rustdoc for every workspace crate (cargo doc --no-deps)
#
# The book's pages link into `api/`, so `build` always produces both halves;
# `serve` rebuilds the API reference first, then runs `mdbook serve`.
#
# Usage:
#   scripts/docs.sh build            # write book/ (+ book/api/)
#   scripts/docs.sh serve [--port N] # serve the book, default http://127.0.0.1:3000
set -euo pipefail

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root" || exit 2

if ! command -v mdbook >/dev/null 2>&1; then
    echo "docs: mdbook is not on PATH. Install it with 'brew install mdbook' or" >&2
    echo "      'cargo install mdbook --version 0.5.4 --locked'." >&2
    exit 2
fi

# cargo doc leaves no workspace landing page, so /api/ would have no entry
# point. Generate one from the crate directories it wrote; everything on it is
# a link into the generated pages, not a copy of their content.
write_api_index() {
    {
        echo '<!DOCTYPE html>'
        echo '<html lang="en"><head><meta charset="utf-8">'
        echo '<title>OpenCompose API reference</title>'
        echo '<style>body{font-family:system-ui,sans-serif;margin:3rem auto;'
        echo 'max-width:52rem;line-height:1.6}code{background:#f0f0f0;padding:0 .2em}</style>'
        echo '</head><body>'
        echo '<h1>OpenCompose API reference</h1>'
        echo '<p>Generated by <code>cargo doc --workspace --no-deps</code> for the'
        echo 'same commit as the <a href="../index.html">book</a>. One page per crate;'
        echo 'the crate-level doc comment is the summary.</p>'
        echo '<ul>'
        for dir in book/api/*/; do
            name=$(basename "$dir")
            [ -f "${dir}index.html" ] || continue
            printf '<li><a href="%s/index.html">%s</a></li>\n' "$name" "$name"
        done
        echo '</ul></body></html>'
    } > book/api/index.html
}

build_book() {
    mdbook build
    echo "docs: book written to book/ (entry point book/index.html)"
}

build_api() {
    # RUSTDOCFLAGS makes a broken intra-doc link a failure, which is the same
    # rule the CI documentation job applies.
    RUSTDOCFLAGS="-D warnings" cargo doc --workspace --no-deps
    # The book is built first and the API reference is copied in afterwards:
    # mdBook cleans its output directory on every build, so a copy made before
    # the build would not survive.
    rm -rf book/api
    mkdir -p book
    cp -R target/doc book/api
    write_api_index
    echo "docs: rustdoc written to book/api/"
}

case "${1:-}" in
    build)
        build_book
        build_api
        ;;
    serve)
        shift || true
        port=3000
        while [ $# -gt 0 ]; do
            case "$1" in
                --port) port=${2:?--port needs a value}; shift 2 ;;
                *) echo "docs: unknown option $1" >&2; exit 2 ;;
            esac
        done
        echo "docs: serving the book on http://127.0.0.1:${port}/" >&2
        echo "docs: mdbook rebuilds book/ on every edit and cleans it, so the" >&2
        echo "      api/ pages are only present after 'scripts/docs.sh build'." >&2
        exec mdbook serve --hostname 127.0.0.1 --port "$port"
        ;;
    *)
        echo "usage: scripts/docs.sh build | serve [--port N]" >&2
        exit 2
        ;;
esac
